use std::collections::BTreeMap;
use std::io::{self, BufRead};

use kfind_morph::{
    ContinuationState, LexicalAlternation, PredicateEntry, PredicatePos, drop_last_final,
    generate_predicate_branches, has_rieul_final,
};

fn main() -> anyhow::Result<()> {
    let object_contrasts = match std::env::args().nth(1).as_deref() {
        None => false,
        Some("--object-contrasts") => true,
        Some(argument) => anyhow::bail!("unknown argument: {argument}"),
    };
    let mut stems = BTreeMap::new();
    let mut verb_objects = BTreeMap::new();
    for row in io::stdin().lock().lines().skip(1) {
        let row = row?;
        let fields: Vec<_> = row.split('\t').collect();
        let [lemma, pos, senses, framed, annotated, object, _] = fields.as_slice() else {
            anyhow::bail!("invalid predicate frame row: {row}");
        };
        let pos = match *pos {
            "VV" => PredicatePos::Verb,
            "VA" => PredicatePos::Adjective,
            _ => anyhow::bail!("invalid predicate POS: {pos}"),
        };
        let alternation = if lemma.ends_with("하다") {
            LexicalAlternation::Ha
        } else {
            LexicalAlternation::Regular
        };
        let entry = PredicateEntry::new(*lemma, pos, alternation);
        let excludes_object =
            *senses != "0" && senses == framed && *annotated == "0" && *object == "0";
        if object_contrasts {
            if pos == PredicatePos::Verb {
                let accepts_object = match *object {
                    "1" => Some(true),
                    "0" if excludes_object => Some(false),
                    _ => None,
                };
                if let Some(accepts_object) = accepts_object {
                    verb_objects.insert((*lemma).to_owned(), accepts_object);
                }
            }
            continue;
        }
        for branch in generate_predicate_branches(&entry)? {
            if matches!(
                branch.continuation,
                ContinuationState::StemEnding | ContinuationState::Past
            ) {
                stems
                    .entry(branch.anchor)
                    .and_modify(|allowed| *allowed &= excludes_object)
                    .or_insert(excludes_object);
            }
        }
    }

    println!("// Generated by the predicate_frame_stems example from audit_predicate_frames.py.");
    println!("&[");
    if object_contrasts {
        let mut contrasts = BTreeMap::new();
        for (lemma, &accepts_object) in &verb_objects {
            let Some(stem) = lemma.strip_suffix('다') else {
                continue;
            };
            if !stem.chars().next_back().is_some_and(has_rieul_final) {
                continue;
            }
            let plain = format!("{}다", drop_last_final(stem).expect("rieul-final stem"));
            if let Some(&other_accepts_object) = verb_objects.get(plain.as_str())
                && accepts_object != other_accepts_object
            {
                let (without_object, with_object) = if accepts_object {
                    (plain, lemma.to_owned())
                } else {
                    (lemma.to_owned(), plain)
                };
                contrasts.insert(without_object, with_object);
            }
        }
        for (without_object, with_object) in contrasts {
            println!("    ({without_object:?}, {with_object:?}),");
        }
    } else {
        for (stem, excludes_object) in stems {
            if excludes_object {
                println!("    {stem:?},");
            }
        }
    }
    println!("]");
    Ok(())
}
