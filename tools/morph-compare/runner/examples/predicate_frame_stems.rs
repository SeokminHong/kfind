use std::collections::BTreeMap;
use std::io::{self, BufRead};

use kfind_morph::{
    ContinuationState, LexicalAlternation, PredicateEntry, PredicatePos,
    generate_predicate_branches,
};

fn main() -> anyhow::Result<()> {
    let mut stems = BTreeMap::new();
    for row in io::stdin().lock().lines().skip(1) {
        let row = row?;
        let fields: Vec<_> = row.split('\t').collect();
        let [lemma, pos, senses, framed, annotated, object, _] = fields.as_slice() else {
            anyhow::bail!("invalid predicate frame row: {row}");
        };
        let pos = match *pos {
            "VV" => PredicatePos::Verb,
            "VA" => PredicatePos::Adjective,
            _ => anyhow::bail!("invalid predicate POS: {pos}"),
        };
        let alternation = if lemma.ends_with("하다") {
            LexicalAlternation::Ha
        } else {
            LexicalAlternation::Regular
        };
        let entry = PredicateEntry::new(*lemma, pos, alternation);
        let excludes_object =
            *senses != "0" && senses == framed && *annotated == "0" && *object == "0";
        for branch in generate_predicate_branches(&entry)? {
            if matches!(
                branch.continuation,
                ContinuationState::StemEnding | ContinuationState::Past
            ) {
                stems
                    .entry(branch.anchor)
                    .and_modify(|allowed| *allowed &= excludes_object)
                    .or_insert(excludes_object);
            }
        }
    }

    println!("// Generated by the predicate_frame_stems example from audit_predicate_frames.py.");
    println!("&[");
    for (stem, excludes_object) in stems {
        if excludes_object {
            println!("    {stem:?},");
        }
    }
    println!("]");
    Ok(())
}
